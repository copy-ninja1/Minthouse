/**
 * Copies the compiled LaunchpadToken ABI and bytecode into
 * `packages/blockchain`, which the web app and API use to deploy and verify
 * tokens. Run after `hardhat compile`. With `--check`, exits non-zero when the
 * committed file is out of date (used in CI).
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { keccak256 } from "viem";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifactPath = path.resolve(here, "../artifacts/contracts/LaunchpadToken.sol/LaunchpadToken.json");
const outputPath = path.resolve(here, "../../../packages/blockchain/src/bsc/generated/launchpad-token.ts");

const hexSchema = z.string().regex(/^0x[0-9a-f]+$/);
const artifactSchema = z.object({
  contractName: z.literal("LaunchpadToken"),
  sourceName: z.string(),
  abi: z.array(z.unknown()),
  bytecode: hexSchema,
  deployedBytecode: hexSchema,
  linkReferences: z.record(z.string(), z.unknown()),
  immutableReferences: z.record(z.string(), z.unknown()),
  buildInfoId: z.string(),
});
const buildInfoSchema = z.object({
  solcVersion: z.string(),
  input: z.object({
    settings: z.object({
      evmVersion: z.string(),
      optimizer: z.object({ enabled: z.boolean(), runs: z.number() }),
    }),
  }),
});

const artifact = artifactSchema.parse(JSON.parse(await readFile(artifactPath, "utf8")));
if (Object.keys(artifact.linkReferences).length > 0 || Object.keys(artifact.immutableReferences).length > 0) {
  throw new Error("LaunchpadToken must not use libraries or immutables: runtime-code verification depends on it.");
}
const buildInfo = buildInfoSchema.parse(
  JSON.parse(await readFile(path.resolve(here, `../artifacts/build-info/${artifact.buildInfoId}.json`), "utf8")),
);

const runtimeCodeHash = keccak256(artifact.deployedBytecode as `0x${string}`);
const compiler = {
  solc: buildInfo.solcVersion,
  evmVersion: buildInfo.input.settings.evmVersion,
  optimizerRuns: buildInfo.input.settings.optimizer.enabled ? buildInfo.input.settings.optimizer.runs : 0,
  sourceName: artifact.sourceName,
};

const contents = `// Generated by chains/bsc/scripts/export-artifacts.ts from the Hardhat build. Do not edit.
export const LAUNCHPAD_TOKEN_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const LAUNCHPAD_TOKEN_BYTECODE = "${artifact.bytecode}" as const;

/** keccak256 of the runtime bytecode. Every LaunchpadToken deployment has exactly this code hash. */
export const LAUNCHPAD_TOKEN_RUNTIME_CODE_HASH = "${runtimeCodeHash}" as const;

export const LAUNCHPAD_TOKEN_COMPILER = ${JSON.stringify(compiler, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== contents) {
    console.error("packages/blockchain LaunchpadToken artifacts are stale. Run `pnpm bsc:export`.");
    process.exit(1);
  }
  console.log("LaunchpadToken artifacts are up to date.");
} else {
  await writeFile(outputPath, contents);
  console.log(`Wrote ${path.relative(process.cwd(), outputPath)} (runtime code hash ${runtimeCodeHash})`);
}
